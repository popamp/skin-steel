# --- 9 x 13: the play time -----------------------------------------------------------
def segments(on):
    """A seven-segment digit; `on` names the lit segments a..g."""
    rows = [["."] * 9 for _ in range(13)]
    horiz = {"a": 0, "g": 6, "d": 12}
    vert = {"f": (0, 1, 5), "b": (7, 1, 5), "e": (0, 7, 11), "c": (7, 7, 11)}
    for s in on:
        if s in horiz:
            for x in range(2, 7):
                rows[horiz[s]][x] = "#"
        else:
            x, y0, y1 = vert[s]
            for y in range(y0, y1 + 1):
                rows[y][x] = rows[y][x + 1] = "#"
    return ["".join(r) for r in rows]


