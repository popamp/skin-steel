# --- output ---------------------------------------------------------------------------
def width(font, text, gap=1):
    return sum(len(font[c][0]) + gap for c in text) - gap


def runs(rows):
    """(x, y, length) of each horizontal run of lit pixels."""
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == "#":
                n = len(row[x:]) - len(row[x:].lstrip("#"))
                yield x, y, n
                x += n
            else:
                x += 1


def svg_text(font, text, x, y, fill, gap=1, anchor="start"):
    """`text` as one SVG path of pixels, its top left at x, y."""
    x -= {"start": 0, "middle": width(font, text, gap) / 2, "end": width(font, text, gap)}[anchor]
    d = []
    for c in text:
        rows = font[c]
        d += [f"M{x + rx} {y + ry}h{n}v1h-{n}z" for rx, ry, n in runs(rows)]
        x += len(rows[0]) + gap
    return f'<path d="{"".join(d)}" fill="{fill}"/>'


def save_ttf(font, path, name, gap=1, rise=0, lower=True):
    """A TrueType font, 100 units to a pixel, whose em is the glyphs'
    height plus `rise` (pixels below the baseline): drawn at that size
    in pixels, every pixel falls on a whole pixel. Lower-case letters get
    the capitals' glyphs."""
    px = 100
    height = len(next(iter(font.values())))
    order = [".notdef"] + [f"u{ord(c):04X}" for c in font]
    fb = FontBuilder((height + rise) * px, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {ord(c): f"u{ord(c):04X}" for c in font}
    if lower:
        for c in font:
            low = c.lower()
            if low != c and len(low) == 1 and ord(low) not in cmap:
                cmap[ord(low)] = f"u{ord(c):04X}"
    fb.setupCharacterMap(cmap)
    glyphs, metrics = {".notdef": TTGlyphPen(None).glyph()}, {".notdef": (0, 0)}
    for c, rows in font.items():
        pen = TTGlyphPen(None)
        for x, y, n in runs(rows):
            top, bottom = (height - y) * px, (height - y - 1) * px
            # Clockwise, as TrueType wants filled contours.
            pen.moveTo((x * px, bottom))
            pen.lineTo((x * px, top))
            pen.lineTo(((x + n) * px, top))
            pen.lineTo(((x + n) * px, bottom))
            pen.closePath()
        name_ = f"u{ord(c):04X}"
        glyphs[name_] = pen.glyph()
        metrics[name_] = ((len(rows[0]) + gap) * px, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=height * px, descent=-rise * px)
    fb.setupNameTable({"familyName": name, "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=height * px, sTypoDescender=-rise * px, usWinAscent=height * px, usWinDescent=rise * px)
    fb.setupPost()
    fb.save(path)
